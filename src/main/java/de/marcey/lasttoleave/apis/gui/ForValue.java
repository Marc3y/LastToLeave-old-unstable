package de.marcey.lasttoleave.apis.gui;

public class ForValue {

    private int from;
    private int to;

    public ForValue(int from, int to){
        this.from = from;
        this.to = to;
    }

    public int getFrom() {
        return from;
    }

    public int getTo() {
        return to;
    }
}
